#!/usr/bin/env node
/**
 * Writes lib/outreach/backend/contract.names.ts: every SQL RPC (`rpc('name')`), edge function (`callFn('name')`) and
 * table (`db.from('table')`) the outreach UI uses. The contract types come from these lists, and the demo handler maps
 * are typed over them, so a new call without its demo side is a TypeScript error (docs/outreach/PRODUCT-TOUR.md).
 *
 *   node scripts/outreach-demo-contract.mjs           rewrite the file
 *   node scripts/outreach-demo-contract.mjs --check   exit 1 when the file is out of date (run by the demo check)
 *
 * Names already in the file are kept (a handler may serve code that builds the name at runtime); pass --prune to drop
 * names no longer found in the source.
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const SCAN = ['app/outreach', 'components/outreach', 'lib/outreach', 'contexts/OutreachWorkspaceContext.tsx', 'components/MainLayout.tsx'];
const SKIP = [/lib[\\/]outreach[\\/]backend[\\/]/, /\.test\.tsx?$/];
const OUT = join(ROOT, 'lib/outreach/backend/contract.names.ts');

function files(p) {
  const abs = join(ROOT, p);
  if (!existsSync(abs)) return [];
  if (statSync(abs).isFile()) return [abs];
  return readdirSync(abs).flatMap((f) => files(join(p, f)));
}

/** Index just after a balanced `<...>` generic starting at `i` (`=>` arrows do not close it). */
function skipGeneric(src, i) {
  let depth = 0;
  for (let j = i; j < src.length; j++) {
    const c = src[j];
    if (c === '<') depth++;
    else if (c === '>' && src[j - 1] !== '=') { depth--; if (depth === 0) return j + 1; }
    if (j - i > 800) return -1;
  }
  return -1;
}

/** First string argument of every `name(` / `name<…>(` call. */
function callNames(src, fn) {
  const out = [];
  const re = new RegExp(`(?<![\\w.$])${fn}\\s*(?=[<(])`, 'g');
  let m;
  while ((m = re.exec(src))) {
    let i = m.index + m[0].length;
    if (src[i] === '<') { i = skipGeneric(src, i); if (i < 0) continue; }
    while (/\s/.test(src[i])) i++;
    if (src[i] !== '(') continue;
    i++;
    while (/\s/.test(src[i])) i++;
    const q = src[i];
    if (q !== "'" && q !== '"' && q !== '`') continue;
    const end = src.indexOf(q, i + 1);
    if (end < 0) continue;
    out.push(src.slice(i + 1, end));
  }
  return out;
}

const rpcs = new Set();
const fns = new Set();
const tables = new Set();
for (const f of SCAN.flatMap(files)) {
  if (!/\.(ts|tsx)$/.test(f) || SKIP.some((r) => r.test(f))) continue;
  const src = readFileSync(f, 'utf8');
  for (const n of callNames(src, 'rpc')) if (/^[a-z0-9_]+$/.test(n)) rpcs.add(n);
  for (const n of callNames(src, 'callFn')) { const base = n.split(/[/?$]/)[0]; if (/^[a-z0-9-]+$/.test(base)) fns.add(base); }
  for (const m of src.matchAll(/\b(?:supabase|db)\s*\.\s*from\(\s*['"]([a-z_]+)['"]/g)) tables.add(m[1]);
  void relative;
}

const prune = process.argv.includes('--prune');
const check = process.argv.includes('--check');
const previous = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
const prevList = (name) => {
  const m = new RegExp(`export const ${name} = \\[([\\s\\S]*?)\\] as const`).exec(previous);
  return m ? [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1]) : [];
};
const missing = { rpc: [...rpcs].filter((n) => !prevList('RPC_NAMES').includes(n)), fn: [...fns].filter((n) => !prevList('FN_NAMES').includes(n)), table: [...tables].filter((n) => !prevList('TABLE_NAMES').includes(n)) };
if (!prune) {
  for (const n of prevList('RPC_NAMES')) rpcs.add(n);
  for (const n of prevList('FN_NAMES')) fns.add(n);
  for (const n of prevList('TABLE_NAMES')) tables.add(n);
}

const list = (name, set) => `export const ${name} = [\n${[...set].sort().map((n) => `  '${n}',`).join('\n')}\n] as const;\n`;
const text = `// GENERATED by scripts/outreach-demo-contract.mjs. Do not edit by hand: run \`npm run demo:contract\`.
// Every name here needs a demo handler (lib/outreach/backend/demo); the build fails until it has one.

${list('RPC_NAMES', rpcs)}
${list('FN_NAMES', fns)}
${list('TABLE_NAMES', tables)}`;

if (check) {
  const stale = missing.rpc.length + missing.fn.length + missing.table.length;
  if (stale) {
    console.error('[demo-contract] used in the outreach UI but missing from contract.names.ts (run npm run demo:contract):');
    for (const [k, v] of Object.entries(missing)) if (v.length) console.error(`  ${k}: ${v.join(', ')}`);
    process.exit(1);
  }
  console.log(`[demo-contract] ok: ${rpcs.size} rpcs, ${fns.size} functions, ${tables.size} tables`);
} else {
  writeFileSync(OUT, text);
  console.log(`[demo-contract] wrote ${relative(ROOT, OUT)}: ${rpcs.size} rpcs, ${fns.size} functions, ${tables.size} tables`);
}
